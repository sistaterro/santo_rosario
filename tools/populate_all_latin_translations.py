def main():
    source = LATIN_PATH.read_text(encoding="utf-8")
    payload = source.split("=", 1)[1].strip()
    if payload.endswith(";"):
        payload = payload[:-1]
    data = json.loads(payload)

    for phrase in data["frases"]:
        pid = phrase["id"]
        tr = phrase.setdefault("translations", {})
        for lang, lang_dict in TRANSLATIONS.items():
            tr[lang] = {
                "text": lang_dict[pid],
                "source": SOURCE,
            }

    output = "window.SANTO_ROSARIO_LATIN = " + json.dumps(data, ensure_ascii=False, indent=2) + ";\n"
    LATIN_PATH.write_text(output, encoding="utf-8")
    print(f"Successfully populated all {len(data['frases'])} Latin phrases across all 12 target languages!")

if __name__ == "__main__":
    main()

